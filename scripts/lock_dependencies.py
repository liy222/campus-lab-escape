"""Lock only the installed dependency closure of backend/requirements.in."""
from importlib import metadata
from pathlib import Path
import sys

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

from scripts.dev import ROOT


def main() -> int:
    roots = [Requirement(line) for line in (ROOT / "backend/requirements.in").read_text(encoding="utf-8").splitlines()
             if line.strip() and not line.lstrip().startswith("#")]
    pending = list(roots)
    locked: dict[str, str] = {}
    while pending:
        requirement = pending.pop()
        if requirement.marker and not requirement.marker.evaluate({"extra": ""}):
            continue
        if requirement.extras:
            raise ValueError("extras are not supported by this minimal lock generator")
        name = canonicalize_name(requirement.name)
        if name in locked:
            if requirement.specifier and not requirement.specifier.contains(locked[name]):
                raise ValueError(f"installed {name}=={locked[name]} does not satisfy {requirement}")
            continue
        distribution = metadata.distribution(name)
        if requirement.specifier and not requirement.specifier.contains(distribution.version):
            raise ValueError(f"installed {name}=={distribution.version} does not satisfy {requirement}")
        locked[name] = distribution.version
        pending.extend(Requirement(value) for value in (distribution.requires or []))
    output = ROOT / "backend/requirements.lock.txt"
    header = f"# Actual installed closure for Python {sys.version.split()[0]} on {sys.platform}.\n# Generated by python -m scripts.lock_dependencies; no unrelated environment packages.\n"
    output.write_text(header + "".join(f"{name}=={version}\n" for name, version in sorted(locked.items())), encoding="utf-8")
    print(f"Locked {len(locked)} distributions: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
